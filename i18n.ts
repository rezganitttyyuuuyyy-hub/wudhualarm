const DICTS: Record<LangCode, Dict> = { ar, en, fr, tr, ur, id, de, es };

export function detectSystemLang(): LangCode {
  try {
    const locales = getLocales();
    const code = locales?.[0]?.languageCode ?? 'en';
    if (code in DICTS) return code as LangCode;
  } catch {
    // ignore
  }
  return 'en';
}

export function getDict(lang: LangCode): Dict {
  return DICTS[lang] ?? en;
}

export function isRtl(lang: LangCode): boolean {
  const def = LANGUAGES.find((l) => l.code === lang);
  return def?.rtl ?? false;
}
